def add(number_1: float, number_2: float) -> float:
    """Add two numbers together and return the sum.

    Parameters:
    number_1: The first number
    number_2: The second number

    Returns:
    float: The sum of the two numbers
    """
    value = number_1 + number_2
    return value


def subtract(number_1: float, number_2: float) -> float:
    """Subtract the second number from the first and return the difference.

    Parameters:
    number_1: The first number
    number_2: The number to subtract

    Returns:
    float: The difference between the two numbers
    """
    value = number_1 - number_2
    return value


def multiply(number_1: float, number_2: float) -> float:
    """Multiply two numbers together and return the product.

    Parameters:
    number_1: The first number
    number_2: The second number

    Returns:
    float: The product of the two numbers
    """
    value = number_1 * number_2
    return value


def divide(number_1: float, number_2: float) -> float:
    """Divide the first number by the second and return the quotient.

    Parameters:
    number_1: The numerator
    number_2: The denominator

    Returns:
    float: The result of the division
    """
    value = number_1 / number_2
    return value